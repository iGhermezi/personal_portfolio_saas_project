export const useI18nStore = defineStore("i18n", {
  state: () => ({
    language: localStorage.getItem(STORAGE_KEY) || "en",
  }),

  getters: {
    isRTL: (state) => state.language === "fa",

    templateName: (state) => (template) => {
      return (
        translations[state.language]?.templates?.catalog?.[
          template?.template_key
        ]?.name ??
        template?.name ??
        ""
      );
    },

    templateDescription: (state) => (template) => {
      return (
        translations[state.language]?.templates?.catalog?.[
          template?.template_key
        ]?.description ??
        template?.description ??
        ""
      );
    },

    t: (state) => {
      return (key) => {
        const parts = key.split(".");
        let value = translations[state.language];

        for (const part of parts) {
          value = value?.[part];
        }

        return value ?? key;
      };
    },
  },

  actions: {
    initializeLanguage() {
      const saved = localStorage.getItem(STORAGE_KEY);

      if (saved === "fa" || saved === "en") {
        this.language = saved;
      } else {
        this.language = "en";
      }

      this.applyLanguage();
    },

    setLanguage(language) {
      if (language !== "fa" && language !== "en") {
        return;
      }

      this.language = language;

      localStorage.setItem(STORAGE_KEY, language);

      this.applyLanguage();
    },

    toggleLanguage() {
      this.setLanguage(this.language === "en" ? "fa" : "en");
    },

    applyLanguage() {
      document.documentElement.lang = this.language;
      document.title = this.t("common.appName");
      document.documentElement.dir = this.isRTL ? "rtl" : "ltr";
    },
  },
});
